import { expect, test } from '@playwright/test'
import { expectRows, readTable } from './helpers'

test('an idle ship is eventually hit; the run is saved once and Play again starts clean', async ({ page }) => {
  test.setTimeout(180_000)
  await page.clock.install({ time: new Date('2026-11-15T10:00:00Z') })
  await page.goto('/play/asteroid-assault?seed=e2e-aa')
  const field = page.locator('.aa-field')
  await expect(field).toBeVisible()
  await page.getByLabel('Difficulty').selectOption('hard')
  await page.keyboard.press('Space')
  await expect(field).toHaveAttribute('data-status', 'playing')
  for (let i = 0; i < 600 && (await field.getAttribute('data-status')) !== 'lost'; i++) await page.clock.runFor(1000)
  await expect(field).toHaveAttribute('data-status', 'lost')
  await expect(page.locator('.game-over').getByRole('heading', { name: 'Ship lost' })).toBeVisible()
  await expectRows(page, 'history', 1)
  const [row] = await readTable(page, 'history')
  expect(row).toMatchObject({ gameId: 'asteroid-assault', won: false })
  await page.clock.runFor(5000)
  await expectRows(page, 'history', 1)
  await page.getByRole('button', { name: 'Play again' }).click()
  await expect(field).toHaveAttribute('data-status', 'ready')
})

test('keys turn the ship, pause freezes it, and the touch buttons work', async ({ page }) => {
  await page.clock.install({ time: new Date('2026-11-15T10:00:00Z') })
  await page.goto('/play/asteroid-assault?seed=e2e-aa-keys')
  const field = page.locator('.aa-field')
  await expect(field).toBeVisible()
  await page.keyboard.press('Space')
  await page.keyboard.down('ArrowRight')
  await page.clock.runFor(300)
  await page.keyboard.up('ArrowRight')
  expect(Number(await field.getAttribute('data-angle'))).toBeGreaterThan(0.5)
  await page.keyboard.press('p')
  await expect(field).toHaveAttribute('data-status', 'paused')
  const angle = await field.getAttribute('data-angle')
  await page.clock.runFor(500)
  expect(await field.getAttribute('data-angle')).toBe(angle)
  await page.keyboard.press('p')
  await expect(field).toHaveAttribute('data-status', 'playing')
  const before = Number(await field.getAttribute('data-angle'))
  const left = page.getByRole('button', { name: 'Turn left' })
  const box = (await left.boundingBox())!
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.down()
  await page.clock.runFor(300)
  await page.mouse.up()
  expect(Number(await field.getAttribute('data-angle'))).toBeLessThan(before)
})
